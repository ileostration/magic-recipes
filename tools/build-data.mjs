// Merges data/batch-*.json into data/recipes.js (an ES module, so the site also works from file://)
// and checks every tag against data/taxonomy.json. Run: node tools/build-data.mjs
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dataDir = resolve(root, 'data');
const tax = JSON.parse(readFileSync(resolve(dataDir, 'taxonomy.json'), 'utf8'));
const files = readdirSync(dataDir).filter((f) => /^batch-.*\.json$/.test(f)).sort();
const all = [];
const ids = new Set();
let bad = 0;
for (const f of files) {
  const arr = JSON.parse(readFileSync(resolve(dataDir, f), 'utf8'));
  for (const r of arr) {
    const where = f + ' / ' + r.id;
    const check = (field, v) => { if (!tax[field].includes(v)) { console.error('bad ' + field + ' "' + v + '" in ' + where); bad++; } };
    if (ids.has(r.id)) { console.error('duplicate id ' + where); bad++; }
    ids.add(r.id);
    check('cuisine', r.cuisine); check('category', r.category); check('dish', r.dish);
    (r.flavors || []).forEach((v) => check('flavors', v));
    (r.mains || []).forEach((v) => check('mains', v));
    (r.method || []).forEach((v) => check('method', v));
    (r.diet || []).forEach((v) => check('diet', v));
    if (!Array.isArray(r.ingredients) || r.ingredients.length < 3) { console.error('too few ingredients ' + where); bad++; }
    if (!Array.isArray(r.steps) || r.steps.length < 3) { console.error('too few steps ' + where); bad++; }
    if (r.wiki && !/^Cookbook:/.test(r.wiki)) { console.error('bad wiki title ' + where); bad++; }
    all.push(r);
  }
}
if (bad) { console.error(bad + ' problem(s)'); process.exit(1); }
const out = '/* Generated by tools/build-data.mjs from data/batch-*.json. Do not edit by hand. */\nexport default ' + JSON.stringify(all, null, 1) + ';\n';
writeFileSync(resolve(dataDir, 'recipes.js'), out);
console.log(all.length + ' recipes -> data/recipes.js');
