// Merges data/batch-*.json with data/images-*.json, data/nutrition.json and data/similar.json into data/recipes.js
// (an ES module, so the site also works from file://) and checks every tag against data/taxonomy.json.
// Run: node tools/build-data.mjs   (after python3 tools/nutrition.py and python3 tools/similarity.py)
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dataDir = resolve(root, 'data');
const read = (f) => JSON.parse(readFileSync(resolve(dataDir, f), 'utf8'));
const tax = read('taxonomy.json');
const files = readdirSync(dataDir).filter((f) => /^batch-.*\.json$/.test(f)).sort();
const images = {};
for (const f of readdirSync(dataDir).filter((x) => /^images-.*\.json$/.test(x))) for (const im of read(f)) images[im.id] = im;
const nutrition = existsSync(resolve(dataDir, 'nutrition.json')) ? read('nutrition.json') : {};
const similar = existsSync(resolve(dataDir, 'similar.json')) ? read('similar.json') : {};

const all = [];
const ids = new Set();
let bad = 0, noImg = 0;
for (const f of files) {
  for (const r of read(f)) {
    const where = f + ' / ' + r.id;
    const check = (field, v) => { if (!tax[field].includes(v)) { console.error('bad ' + field + ' "' + v + '" in ' + where); bad++; } };
    if (ids.has(r.id)) { console.error('duplicate id ' + where); bad++; }
    ids.add(r.id);
    check('cuisine', r.cuisine); check('category', r.category); check('dish', r.dish);
    (r.flavors || []).forEach((v) => check('flavors', v));
    (r.mains || []).forEach((v) => check('mains', v));
    (r.method || []).forEach((v) => check('method', v));
    (r.diet || []).forEach((v) => check('diet', v));
    (r.goal || []).forEach((v) => check('goal', v));
    if (!Array.isArray(r.ingredients) || r.ingredients.length < 3) { console.error('too few ingredients ' + where); bad++; }
    if (!Array.isArray(r.steps) || r.steps.length < 3) { console.error('too few steps ' + where); bad++; }
    const im = images[r.id];
    if (im) r.image = { url: im.url, thumb: im.thumb, alt: im.alt, credit: { name: im.credit.name, link: im.credit.link }, page: im.page, source: 'unsplash' };
    else { noImg++; console.error('no image for ' + where); }
    r.goal = r.goal || [];
    if (nutrition[r.id]) r.nutrition = nutrition[r.id];
    if (similar[r.id]) r.similar = similar[r.id];
    all.push(r);
  }
}
if (bad) { console.error(bad + ' problem(s)'); process.exit(1); }
if (noImg) { console.error(noImg + ' recipe(s) without a photo'); process.exit(1); }
const out = '/* Generated by tools/build-data.mjs from data/batch-*.json, images-*.json, nutrition.json, similar.json. Do not edit by hand. */\nexport default ' + JSON.stringify(all) + ';\n';
writeFileSync(resolve(dataDir, 'recipes.js'), out);
console.log(all.length + ' recipes -> data/recipes.js');
